function teaCoasterPhotos(
  pattern: (typeof TEA_COASTER_PATTERNS)[number],
  view: "individual" | "set4" | "set6",
): string[] {
  const photos = pattern[view];
  if (photos.length > 0) return [...photos];
  return [pattern.individual[0]];
}

export function teaCoasterMatchForImage(imageUrl: string) {
  return (
    TEA_COASTER_PATTERNS.find((pattern) =>
      (["individual", "set4", "set6"] as const).some((view) =>
        (pattern[view] as readonly string[]).includes(imageUrl),
      ),
    ) ?? null
  );
}

export function teaCoasterLabelForImage(imageUrl: string): string | null {
  return teaCoasterMatchForImage(imageUrl)?.name ?? null;
}

export function teaCoasterImagesForView(
  patternImage: string,
  view: "individual" | "set4" | "set6",
): string[] | undefined {
  const match = teaCoasterMatchForImage(patternImage);
  if (!match) return undefined;
  return teaCoasterPhotos(match, view);
}

export function teaCoasterImageForView(
  patternImage: string,
  view: "individual" | "set4" | "set6",
): string | undefined {
  return teaCoasterImagesForView(patternImage, view)?.[0];
}


